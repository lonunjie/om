//! The chat-history backup file (ADR-0184): format vectors, every refusal with its own typed error, no partial import,
//! no secrets in the file, and a restored profile that can read old history and nothing else.

mod common;

use om_core::api::*;
use om_core::backup::{self, BackupError, BackupPlan, Kdf};
use om_core::host::{CoreError, Step};
use om_core::runtime::{LoopbackNetwork, Runtime, settle_all};

const KEY: [u8; 32] = [0x42; 32];
const OTHER_KEY: [u8; 32] = [0x43; 32];

fn test_kdf() -> Kdf {
    Kdf {
        m_kib: 64,
        t: 1,
        p: 1,
    }
}

// ----------------------------------------------------------------------------------------------- the file format

fn sample_body() -> Vec<u8> {
    let a = backup::HistoryArchive {
        exported_at_ms: 1_790_000_123_000,
        owner_label: "Alice".into(),
        chats: vec![backup::ArchivedChat {
            id: "c-1".into(),
            display_name: "Bob".into(),
            peer_account_id: "11".repeat(32),
            created_at: 1_789_999_000_000,
            canon_id: "22".repeat(32),
            messages: vec![
                backup::ArchivedMsg {
                    id: "m-1".into(),
                    outgoing: true,
                    text: "Hello, Bob".into(),
                    sent_at: 1_789_999_100_000,
                    delivery: 2,
                    clock_ms: 1_789_999_100_000,
                    clock_logical: 0,
                    digest: "33".repeat(32),
                },
                backup::ArchivedMsg {
                    id: "m-2".into(),
                    outgoing: false,
                    text: "Hi Alice \u{1F44B}".into(),
                    sent_at: 1_789_999_200_000,
                    delivery: 2,
                    clock_ms: 1_789_999_200_000,
                    clock_logical: 1,
                    digest: String::new(),
                },
            ],
        }],
    };
    backup::encode_body(&a)
}

fn sample_file() -> Vec<u8> {
    backup::seal(&sample_body(), test_kdf(), &[7; 16], &[9; 24], &KEY).unwrap()
}

#[test]
fn the_documented_vector_is_stable() {
    // OMB-1 test vector: fixed key, salt and nonce give exactly these bytes. A change here is a format change and
    // needs a new version byte (ADR-0184), never a quiet edit of the vector.
    let f = sample_file();
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../verification/vectors/om-backup-file-vectors.json"
    );
    let current = serde_json::json!({
        "format": "OMB-1",
        "note": "Generated by crates/om-core/tests/backup.rs with OM_WRITE_VECTORS=1. master is the Argon2id output (here a constant); the test build uses token KDF settings, a real writer uses m=65536, t=3, p=1.",
        "master": om_core::crypto::hex(&KEY),
        "kdf": {"m_kib": 64, "t": 1, "p": 1},
        "salt": om_core::crypto::hex(&[7; 16]),
        "nonce": om_core::crypto::hex(&[9; 24]),
        "body": om_core::crypto::hex(&sample_body()),
        "file": om_core::crypto::hex(&f),
        "wrong_master": om_core::crypto::hex(&OTHER_KEY),
    });
    if std::env::var("OM_WRITE_VECTORS").is_ok() {
        std::fs::write(path, serde_json::to_string_pretty(&current).unwrap() + "\n").unwrap();
    }
    let committed: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    assert_eq!(committed, current);
    // And the committed file opens to the committed body, from the committed key.
    let file = om_core::crypto::unhex(committed["file"].as_str().unwrap()).unwrap();
    let body = backup::open(&file, &KEY).unwrap();
    assert_eq!(
        om_core::crypto::hex(&body),
        committed["body"].as_str().unwrap()
    );
    assert_eq!(&file[..8], b"OMBACKUP");
    assert_eq!(file.len(), backup::HEADER_LEN + body.len() + 16);
}

#[test]
fn round_trip_and_the_body_decodes_to_what_was_written() {
    let f = sample_file();
    let h = backup::inspect(&f).unwrap();
    assert_eq!(
        (h.version, h.profile, h.kdf, h.salt.as_slice()),
        (1, 1, test_kdf(), &[7u8; 16][..])
    );
    let body = backup::open(&f, &KEY).unwrap();
    let a = backup::decode_body(&body).unwrap();
    assert_eq!(a.owner_label, "Alice");
    assert_eq!(a.chats[0].messages.len(), 2);
    assert_eq!(a.chats[0].messages[1].text, "Hi Alice \u{1F44B}");
    assert_eq!(
        backup::encode_body(&a),
        body,
        "deterministic: decode then encode is the identity"
    );
}

