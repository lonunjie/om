// ----------------------------------------------------------------------------------------------- through Core

struct Pair {
    alice: Runtime,
    a: ProfileExecutionContext,
    bob: Runtime,
    b: ProfileExecutionContext,
}

fn pair() -> Pair {
    let net = LoopbackNetwork::default();
    let mut alice = Runtime::new("alice", &net);
    let mut bob = Runtime::new("bob", &net);
    let a = common::create_profile(&mut alice, "pa", "Alice");
    let b = common::create_profile(&mut bob, "pb", "Bob");
    alice.dispatch(&a, "inv", IntentBody::CreateInvite);
    alice.flush_net(&a);
    let link = alice
        .query::<Option<InviteView>>(Query::GetInvite {
            ctx: a.clone(),
            operation_id: "inv".into(),
        })
        .unwrap()
        .link;
    bob.dispatch(&b, "acc", IntentBody::AcceptInvitation { link });
    settle_all(&mut [(&mut alice, &a), (&mut bob, &b)]);
    let intros: Vec<IntroductionRequest> = alice.query(Query::GetIntroductions { ctx: a.clone() });
    alice.dispatch(
        &a,
        "ok",
        IntentBody::AcceptIntroduction {
            request_id: intros[0].id.clone(),
        },
    );
    settle_all(&mut [(&mut alice, &a), (&mut bob, &b)]);
    Pair { alice, a, bob, b }
}

fn conv_id(rt: &Runtime, ctx: &ProfileExecutionContext) -> String {
    let l: Vec<ConversationSummary> = rt.query(Query::GetConversationList { ctx: ctx.clone() });
    l[0].id.clone()
}

fn say(rt: &mut Runtime, ctx: &ProfileExecutionContext, op: &str, text: &str) {
    let id = conv_id(rt, ctx);
    rt.dispatch(
        ctx,
        op,
        IntentBody::SendMessage {
            conversation_id: id,
            draft: Draft { text: text.into() },
        },
    );
}

fn talk(p: &mut Pair) {
    say(&mut p.alice, &p.a.clone(), "s1", "Hello, Bob");
    settle_all(&mut [(&mut p.alice, &p.a), (&mut p.bob, &p.b)]);
    say(&mut p.bob, &p.b.clone(), "s2", "Hi Alice \u{1F44B}");
    settle_all(&mut [(&mut p.alice, &p.a), (&mut p.bob, &p.b)]);
    say(&mut p.alice, &p.a.clone(), "s3", "Lunch tomorrow?");
    settle_all(&mut [(&mut p.alice, &p.a), (&mut p.bob, &p.b)]);
}

fn export(rt: &mut Runtime, ctx: &ProfileExecutionContext, key: &[u8; 32]) -> Vec<u8> {
    let plan: BackupPlan = rt.core.backup_plan();
    rt.core.export_history(ctx, &plan, key).unwrap()
}

fn import(
    rt: &mut Runtime,
    ctx: &ProfileExecutionContext,
    file: &[u8],
    key: &[u8; 32],
) -> Result<backup::ImportSummary, CoreError> {
    let (summary, commit) = rt.core.import_history(ctx, file, key)?;
    assert!(rt.settle(&Step {
        commit,
        handle: None
    }));
    Ok(summary)
}

fn list(rt: &Runtime, ctx: &ProfileExecutionContext) -> Vec<ConversationSummary> {
    rt.query(Query::GetConversationList { ctx: ctx.clone() })
}

fn view(rt: &Runtime, ctx: &ProfileExecutionContext, id: &str) -> ConversationView {
    rt.query(Query::GetConversationView {
        ctx: ctx.clone(),
        conversation_id: id.into(),
    })
}

fn texts(v: &ConversationView) -> Vec<String> {
    v.timeline
        .iter()
        .map(|t| match t {
            TimelineItem::Outgoing { text, .. } | TimelineItem::Incoming { text, .. } => {
                text.clone()
            }
        })
        .collect()
}

#[test]
fn a_fresh_device_can_read_the_old_history_and_nothing_else() {
    let mut p = pair();
    talk(&mut p);
    let file = export(&mut p.alice, &p.a.clone(), &KEY);
    let old_id = conv_id(&p.alice, &p.a);

    // A brand-new install: a different Runtime, a new identity, a different network.
    let mut fresh = Runtime::new("fresh-phone", &LoopbackNetwork::default());
    let f = common::create_profile(&mut fresh, "pf", "Alice again");
    assert!(list(&fresh, &f).is_empty());
    let s = import(&mut fresh, &f, &file, &KEY).unwrap();
    assert_eq!(
        (
            s.chats_added,
            s.chats_updated,
            s.chats_skipped,
            s.messages_added
        ),
        (1, 0, 0, 3)
    );

    let l = list(&fresh, &f);
    assert_eq!(l.len(), 1);
    assert_eq!(l[0].relationship, RelationshipStateCode::Restored);
    assert_eq!(l[0].id, old_id);
    assert_eq!(l[0].display_name, "Bob");
    let v = view(&fresh, &f, &old_id);
    assert_eq!(
        texts(&v),
        ["Hello, Bob", "Hi Alice \u{1F44B}", "Lunch tomorrow?"]
    );

    // It cannot send as the old identity, retry, or be polled: it is not a relationship.
    fresh.dispatch(
        &f,
        "try",
        IntentBody::SendMessage {
            conversation_id: old_id.clone(),
            draft: Draft { text: "hi".into() },
        },
    );
    assert!(matches!(
        fresh.outcome(&f, "try"),
        Some(OutcomeClass::Rejected { .. })
    ));
    assert!(
        fresh
            .core
            .net_ops(&f)
            .unwrap()
            .iter()
            .all(|o| !format!("{:?}", o.call).contains("Deposit"))
    );
    assert!(fresh.core.poll_targets(&f).unwrap().is_empty());

    // The restored profile is a different account: its own device identity is untouched by the import.
    let app = common::app_state(&fresh, &f);
    assert!(app["relationships"].as_object().unwrap().is_empty());
    assert_eq!(app["restored"].as_object().unwrap().len(), 1);
    assert_eq!(app["label"], "Alice again");
}

#[test]
fn the_file_holds_history_and_no_secret_or_route_material() {
    let mut p = pair();
    talk(&mut p);
    let file = export(&mut p.alice, &p.a.clone(), &KEY);
    let body = backup::open(&file, &KEY).unwrap();
    let state = common::app_state(&p.alice, &p.a);

    // Every long hex string anywhere in Alice's profile state (seeds, keys, mailboxes, bindings, credentials), except
    // the few public display hints the backup carries on purpose, must be absent from the plaintext body.
    let allowed: std::collections::BTreeSet<String> = {
        let r = state["relationships"]
            .as_object()
            .unwrap()
            .values()
            .next()
            .unwrap();
        let mut a = vec![
            r["peerAccountId"].as_str().unwrap().to_string(),
            r["canonId"].as_str().unwrap().to_string(),
        ];
        a.extend(
            r["messages"]
                .as_array()
                .unwrap()
                .iter()
                .map(|m| m["digest"].as_str().unwrap().to_string()),
        );
        a.into_iter().collect()
    };
    let mut strings = vec![];
    fn walk(v: &serde_json::Value, out: &mut Vec<String>) {
        match v {
            serde_json::Value::String(s) => out.push(s.clone()),
            serde_json::Value::Array(a) => a.iter().for_each(|x| walk(x, out)),
            serde_json::Value::Object(o) => o.values().for_each(|x| walk(x, out)),
            _ => {}
        }
    }
    walk(&state, &mut strings);
    let mut checked = 0;
    for s in strings {
        if s.len() < 32 || !s.chars().all(|c| c.is_ascii_hexdigit()) || allowed.contains(&s) {
            continue;
        }
        let raw = om_core::crypto::unhex(&s).unwrap();
        assert!(
            !body.windows(raw.len()).any(|w| w == raw.as_slice()),
            "secret-looking value leaked into the backup: {}",
            &s[..16]
        );
        assert!(!String::from_utf8_lossy(&body).contains(&s));
        checked += 1;
    }
    assert!(
        checked > 10,
        "the profile really holds many key and route values ({checked})"
    );
    // The device (private key) record is a different record entirely and is not read by the exporter.
    let text = String::from_utf8_lossy(&body);
    for field in [
        "seed",
        "Seed",
        "mailbox",
        "Mailbox",
        "relay",
        "credential",
        "envelope",
        "outbox",
        "acs",
    ] {
        assert!(!text.contains(field), "{field}");
    }
}

