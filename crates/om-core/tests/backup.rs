#[test]
fn refused_files_import_nothing_and_say_why() {
    let mut p = pair();
    talk(&mut p);
    let file = export(&mut p.alice, &p.a.clone(), &KEY);
    let mut fresh = Runtime::new("fresh", &LoopbackNetwork::default());
    let f = common::create_profile(&mut fresh, "pf", "A");
    let before = fresh.store.records("pf");

    let mut flipped = file.clone();
    *flipped.last_mut().unwrap() ^= 1;
    let mut cut = file.clone();
    cut.truncate(file.len() - 5);
    let cases: [(&str, Vec<u8>, [u8; 32], BackupError); 4] = [
        (
            "wrong password",
            file.clone(),
            OTHER_KEY,
            BackupError::WrongPassword,
        ),
        ("tampered", flipped, KEY, BackupError::Tampered),
        ("truncated", cut, KEY, BackupError::Truncated),
        (
            "not a backup",
            b"hello".to_vec(),
            KEY,
            BackupError::NotABackup,
        ),
    ];
    for (name, bytes, key, want) in cases {
        match import(&mut fresh, &f, &bytes, &key) {
            Err(CoreError::Backup(e)) => assert_eq!(e, want, "{name}"),
            other => panic!("{name}: {other:?}"),
        }
        assert!(list(&fresh, &f).is_empty(), "{name}: nothing was imported");
        assert_eq!(
            fresh.store.records("pf"),
            before,
            "{name}: nothing was written"
        );
    }
    // A key of the wrong size is a caller error, not a password error.
    assert!(matches!(
        fresh.core.import_history(&f, &file, &[1; 5]),
        Err(CoreError::Invalid(_))
    ));
}

#[test]
fn an_authentic_file_with_bad_contents_imports_nothing() {
    let mut p = pair();
    talk(&mut p);
    let mut a = backup::decode_body(
        &backup::open(&export(&mut p.alice, &p.a.clone(), &KEY), &KEY).unwrap(),
    )
    .unwrap();
    a.chats[0].messages[0].id = a.chats[0].messages[1].id.clone();
    let hostile = backup::seal(
        &backup::encode_body(&a),
        test_kdf(),
        &[1; 16],
        &[2; 24],
        &KEY,
    )
    .unwrap();
    let mut fresh = Runtime::new("fresh", &LoopbackNetwork::default());
    let f = common::create_profile(&mut fresh, "pf", "A");
    assert!(matches!(
        import(&mut fresh, &f, &hostile, &KEY),
        Err(CoreError::Backup(BackupError::InvalidContent))
    ));
    assert!(list(&fresh, &f).is_empty());
}

#[test]
fn a_failed_commit_leaves_nothing_restored() {
    let mut p = pair();
    talk(&mut p);
    let file = export(&mut p.alice, &p.a.clone(), &KEY);
    let mut fresh = Runtime::new("fresh", &LoopbackNetwork::default());
    let f = common::create_profile(&mut fresh, "pf", "A");
    fresh.store.fail_next_commit();
    let (_, commit) = fresh.core.import_history(&f, &file, &KEY).unwrap();
    assert!(!fresh.settle(&Step {
        commit,
        handle: None
    }));
    assert!(
        list(&fresh, &f).is_empty(),
        "commit before release: the host could not store it, so it never appeared"
    );
}

