#[test]
fn unknown_versions_profiles_flags_and_costs_are_refused_by_name() {
    let f = sample_file();
    let with = |i: usize, v: u8| {
        let mut g = f.clone();
        g[i] = v;
        g
    };
    assert_eq!(
        backup::open(&with(8, 2), &KEY),
        Err(BackupError::UnsupportedVersion(2))
    );
    assert_eq!(
        backup::open(&with(9, 2), &KEY),
        Err(BackupError::UnsupportedProfile(2))
    );
    assert_eq!(
        backup::open(&with(10, 1), &KEY),
        Err(BackupError::UnsupportedParameters)
    );
    assert_eq!(
        backup::open(&with(11, 1), &KEY),
        Err(BackupError::UnsupportedParameters)
    );
    // Cost fields: p = 0, t = 0 and an enormous memory request are refused before any key work.
    let mut g = f.clone();
    g[20..24].copy_from_slice(&0u32.to_be_bytes());
    assert_eq!(backup::inspect(&g), Err(BackupError::UnsupportedParameters));
    let mut g = f.clone();
    g[12..16].copy_from_slice(&u32::MAX.to_be_bytes());
    assert_eq!(backup::inspect(&g), Err(BackupError::UnsupportedParameters));
    let mut g = f.clone();
    g[16..20].copy_from_slice(&0u32.to_be_bytes());
    assert_eq!(backup::inspect(&g), Err(BackupError::UnsupportedParameters));
}

#[test]
fn the_production_cost_floor_and_ceiling() {
    let k = |m_kib, t, p| Kdf { m_kib, t, p };
    // Floor 64 MiB / 3 passes, ceiling 256 MiB / 10 passes / 4 lanes (what the web vault's policy uses).
    assert!(backup::kdf_in_bounds(&k(65_536, 3, 1), false));
    assert!(backup::kdf_in_bounds(&k(262_144, 10, 4), false));
    for bad in [
        k(65_535, 3, 1),
        k(65_536, 2, 1),
        k(262_145, 3, 1),
        k(65_536, 11, 1),
        k(65_536, 3, 0),
        k(65_536, 3, 5),
    ] {
        assert!(!backup::kdf_in_bounds(&bad, false), "{bad:?}");
    }
    // The test-build floor is only reachable with the insecure test RNG, which a production build cannot contain.
    assert!(backup::kdf_in_bounds(&k(64, 1, 1), true));
    assert!(!backup::kdf_in_bounds(&k(7, 1, 1), true));
    assert_eq!(
        backup::default_kdf(),
        test_kdf(),
        "this test build uses token costs"
    );
}

#[test]
fn any_changed_byte_is_caught_and_none_is_accepted() {
    let f = sample_file();
    let mut seen = std::collections::BTreeMap::<&'static str, u32>::new();
    for i in 0..f.len() {
        let mut g = f.clone();
        g[i] ^= 0x01;
        let err = backup::open(&g, &KEY).expect_err(&format!("byte {i}"));
        let class = match err {
            BackupError::NotABackup => "not_a_backup",
            BackupError::UnsupportedVersion(_) => "version",
            BackupError::UnsupportedProfile(_) => "profile",
            BackupError::UnsupportedParameters => "parameters",
            BackupError::Truncated => "truncated",
            BackupError::Malformed => "malformed",
            BackupError::WrongPassword => "wrong_password",
            BackupError::Tampered => "tampered",
            e => panic!("unexpected {e:?} at {i}"),
        };
        *seen.entry(class).or_default() += 1;
        // The nonce, the declared length and the ciphertext are covered by the AEAD: altering them with the right key
        // is "tampered" (or a length error), never "wrong password".
        if (40..64).contains(&i) || i >= backup::HEADER_LEN {
            assert_eq!(err, BackupError::Tampered, "byte {i}");
        }
    }
    assert!(seen.contains_key("tampered") && seen.contains_key("wrong_password"));
}

#[test]
fn a_sealed_body_with_a_broken_structure_is_invalid_content_not_a_crash() {
    let mut good = backup::decode_body(&sample_body()).unwrap();
    good.chats[0].messages[1].id = good.chats[0].messages[0].id.clone(); // duplicate message id
    assert_eq!(
        backup::decode_body(&backup::encode_body(&good)),
        Err(BackupError::InvalidContent)
    );
    for junk in [&b""[..], b"\xff", b"\xa0", &[0xa1, 0x00, 0x00][..]] {
        assert_eq!(backup::decode_body(junk), Err(BackupError::InvalidContent));
    }
    let mut long = backup::decode_body(&sample_body()).unwrap();
    long.chats[0].messages[0].text = "x".repeat(backup::MAX_TEXT_BYTES + 1);
    assert_eq!(
        backup::decode_body(&backup::encode_body(&long)),
        Err(BackupError::InvalidContent)
    );
    let mut ctrl = backup::decode_body(&sample_body()).unwrap();
    ctrl.chats[0].display_name = "Bob\u{0007}".into();
    assert_eq!(
        backup::decode_body(&backup::encode_body(&ctrl)),
        Err(BackupError::InvalidContent)
    );
}

