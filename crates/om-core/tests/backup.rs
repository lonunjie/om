#[test]
fn deleted_messages_are_not_exported() {
    let mut p = pair();
    talk(&mut p);
    // Tombstone one message the way an author's delete does, by marking it in the committed state through a restart.
    let mut app = common::app_state(&p.alice, &p.a);
    app["relationships"]
        .as_object_mut()
        .unwrap()
        .values_mut()
        .next()
        .unwrap()["messages"][0]["deleted"] = true.into();
    let st: om_core::state::AppState = serde_json::from_value(app).unwrap();
    let archive = backup::collect(&st, 1).unwrap();
    assert_eq!(archive.chats[0].messages.len(), 2);
}
