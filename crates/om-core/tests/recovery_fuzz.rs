//! V-012 hardening for the owner-recovery codecs and the link-ceremony frames: replay of the committed seed corpus and a
//! small deterministic mutation smoke over the byte-slice entry points in `om_core::recovery_fuzz_entry`. The long
//! coverage-guided runs are the libFuzzer targets in `verification/prototypes/recovery-fuzz`; this file is the offline
//! smoke layer and the regression gate for every input those runs keep.

use om_core::crypto::unhex;
use om_core::recovery_fuzz_entry::TARGETS;
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::time::{Duration, Instant};

const ARCHIVE: &[u8] =
    include_bytes!("../../../verification/prototypes/recovery-fuzz/seeds.json.gz");
const PER_INPUT: Duration = Duration::from_secs(1);

/// The committed seed corpus: `{target: {file name: hex}}`, regenerated by `gen_seed_corpus.py`.
fn seeds(target: &str) -> Vec<(String, Vec<u8>)> {
    let doc: serde_json::Value =
        serde_json::from_reader(flate2::read::GzDecoder::new(ARCHIVE)).expect("seed archive");
    let files = doc[target]
        .as_object()
        .unwrap_or_else(|| panic!("no seeds for {target}"));
    let mut out: Vec<_> = files
        .iter()
        .map(|(name, hexed)| (name.clone(), unhex(hexed.as_str().unwrap()).unwrap()))
        .collect();
    out.sort();
    out
}

#[test]
fn every_seed_meets_its_expectation_without_a_crash_or_a_hang() {
    let mut mismatches = Vec::new();
    for (target, run) in TARGETS {
        let all = seeds(target);
        assert!(
            all.len() >= 9,
            "{target}: seed corpus is too small ({})",
            all.len()
        );
        for (name, data) in &all {
            let started = Instant::now();
            let result = run(data);
            assert!(
                started.elapsed() < PER_INPUT,
                "{target}/{name}: over 1 second"
            );
            if name.starts_with("ok-") && result.is_err() {
                mismatches.push(format!("{target}/{name}: expected accept, got {result:?}"));
            } else if name.starts_with("bad-") && result.is_ok() {
                mismatches.push(format!("{target}/{name}: expected refusal"));
            }
        }
    }
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
}

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n.max(1) as u64) as usize
    }
}

/// A short deterministic mutation pass: every target survives a few thousand byte-level edits of its own seeds.
#[test]
fn mutated_seeds_never_panic_or_hang() {
    let mut rng = Rng(0x005e_ed0f_u64 | 1);
    for (target, run) in TARGETS {
        let pool: Vec<Vec<u8>> = seeds(target)
            .into_iter()
            .map(|(_, d)| d)
            .filter(|d| d.len() <= 70_000)
            .collect();
        for _ in 0..1500 {
            let mut data = pool[rng.below(pool.len())].clone();
            for _ in 0..=rng.below(3) {
                let n = data.len();
                match rng.below(5) {
                    0 if n > 0 => data[rng.below(n)] ^= 1 << rng.below(8),
                    1 if n > 0 => data[rng.below(n)] = rng.next() as u8,
                    2 if n > 0 => data.truncate(rng.below(n)),
                    3 => {
                        let at = rng.below(n + 1);
                        data.insert(at, rng.next() as u8);
                    }
                    _ if n > 1 => {
                        let at = rng.below(n - 1);
                        data.remove(at);
                    }
                    _ => {}
                }
            }
            let started = Instant::now();
            if catch_unwind(AssertUnwindSafe(|| {
                let _ = run(&data);
            }))
            .is_err()
            {
                panic!(
                    "{target}: entry point panicked (smoke input of {} bytes)",
                    data.len()
                );
            }
            assert!(started.elapsed() < PER_INPUT, "{target}: over 1 second");
        }
    }
}
