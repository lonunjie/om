//! V-012 hardening (ADR-0251): replay of the committed seed corpus, a small in-tree mutation driver and property
//! checks over the expressive-media parsers. The long coverage-guided runs are the libFuzzer targets in
//! `verification/prototypes/expressive-fuzz`; this file is the offline smoke layer and the regression gate for
//! every input those runs keep.
//!
//! Environment for the ignored long run, normally set by `verification/prototypes/expressive-fuzz/run_fuzz.py`:
//! `OM_FUZZ_TARGET`, `OM_FUZZ_SECONDS`, `OM_FUZZ_SEED`, `OM_FUZZ_ARTIFACTS`.

use om_core::crypto::unhex;
use om_core::expressive::fuzz_entry::{self, TARGETS};
use om_core::expressive::{Frame, Kind, validate_facts};
use proptest::prelude::*;
use std::panic::{AssertUnwindSafe, catch_unwind};
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

type Entry = fn(&[u8]) -> Result<(), &'static str>;

const ARCHIVE: &[u8] =
    include_bytes!("../../../verification/prototypes/expressive-fuzz/seeds.json.gz");

fn entry(name: &str) -> Entry {
    TARGETS
        .iter()
        .find(|(n, _)| *n == name)
        .unwrap_or_else(|| panic!("unknown target {name}"))
        .1
}

/// The committed seed corpus: `{target: {file name: hex}}`, regenerated by `gen_seed_corpus.py`.
fn seeds(target: &str) -> Vec<(String, Vec<u8>)> {
    let doc: serde_json::Value =
        serde_json::from_reader(flate2::read::GzDecoder::new(ARCHIVE)).expect("seed archive");
    let files = doc[target]
        .as_object()
        .unwrap_or_else(|| panic!("no seeds for {target}"));
    let mut out: Vec<_> = files
        .iter()
        .map(|(name, hexed)| (name.clone(), unhex(hexed.as_str().unwrap()).unwrap()))
        .collect();
    out.sort();
    out
}

/// The ADR-0251 "hang over 1 second per input" bound, checked on every replayed seed.
const PER_INPUT: Duration = Duration::from_secs(1);

#[test]
fn every_seed_meets_its_expectation_without_a_crash_or_a_hang() {
    let mut mismatches = Vec::new();
    for (target, run) in TARGETS {
        let all = seeds(target);
        assert!(
            all.len() >= 30,
            "{target}: seed corpus is too small ({})",
            all.len()
        );
        let (mut ok, mut bad) = (0, 0);
        for (name, data) in &all {
            let started = Instant::now();
            let result = run(data);
            assert!(
                started.elapsed() < PER_INPUT,
                "{target}/{name}: over 1 second"
            );
            if name.starts_with("ok-") {
                if result.is_err() {
                    mismatches.push(format!("{target}/{name}: expected accept, got {result:?}"));
                }
                ok += 1;
            } else if name.starts_with("bad-") {
                if result.is_ok() {
                    mismatches.push(format!("{target}/{name}: expected refusal"));
                }
                bad += 1;
            }
        }
        // Both verdicts are present for every target whose frozen vectors have both.
        if target != "event" {
            assert!(ok > 0, "{target}: no accepted seed");
        }
        if !matches!(target, "webp" | "pack_file" | "control_state") {
            assert!(bad > 0, "{target}: no refused seed");
        }
    }
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
}

// ------------------------------------------------------------------------------------------- mutation driver

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n.max(1) as u64) as usize
    }
}

const INTERESTING: [u8; 10] = [0x00, 0x01, 0x7f, 0x80, 0xff, 0x17, 0x18, 0x19, 0x1a, 0x1b];

fn mutate(rng: &mut Rng, pool: &[Vec<u8>], max_len: usize) -> Vec<u8> {
    let mut data = pool[rng.below(pool.len())].clone();
    for _ in 0..=rng.below(4) {
        let n = data.len();
        match rng.below(8) {
            0 if n > 0 => data[rng.below(n)] ^= 1 << rng.below(8),
            1 if n > 0 => data[rng.below(n)] = rng.next() as u8,
            2 if n > 0 => data[rng.below(n)] = INTERESTING[rng.below(INTERESTING.len())],
            3 if n > 0 => {
                let at = rng.below(n);
                data.truncate(at);
            }
            4 if n > 0 => {
                let (at, len) = (rng.below(n), 1 + rng.below(8));
                let end = (at + len).min(n);
                data.drain(at..end);
            }
            5 => {
                let at = rng.below(n + 1);
                for _ in 0..1 + rng.below(8) {
                    data.insert(at, rng.next() as u8);
                }
            }
            6 if n > 0 => {
                let (from, len) = (rng.below(n), 1 + rng.below(64));
                let piece: Vec<u8> = data[from..(from + len).min(n)].to_vec();
                let at = rng.below(n + 1);
                data.splice(at..at, piece);
            }
            _ => {
                let other = &pool[rng.below(pool.len())];
                if !other.is_empty() {
                    let (from, len) = (rng.below(other.len()), 1 + rng.below(128));
                    let piece = &other[from..(from + len).min(other.len())];
                    let at = rng.below(data.len() + 1);
                    data.splice(at..at, piece.iter().copied());
                }
            }
        }
        data.truncate(max_len);
    }
    data
}

/// Run one target for `iterations` inputs, or until `deadline`. Returns the number of inputs executed. A panic or
/// an input slower than the per-input bound is written to `artifacts` and fails the run.
fn drive(
    target: &str,
    seed: u64,
    iterations: u64,
    deadline: Option<Instant>,
    artifacts: Option<&Path>,
) -> u64 {
    let run = entry(target);
    let pool: Vec<Vec<u8>> = seeds(target).into_iter().map(|(_, d)| d).collect();
    let mut rng = Rng(seed | 1);
    let max_len = if target == "pack_file" {
        1 << 18
    } else {
        1 << 16
    };
    let mut executed = 0;
    while executed < iterations && deadline.is_none_or(|d| Instant::now() < d) {
        let input = mutate(&mut rng, &pool, max_len);
        let started = Instant::now();
        let outcome = catch_unwind(AssertUnwindSafe(|| run(&input)));
        let slow = started.elapsed() >= PER_INPUT;
        if outcome.is_err() || slow {
            let kind = if outcome.is_err() { "crash" } else { "slow" };
            if let Some(dir) = artifacts {
                std::fs::create_dir_all(dir).unwrap();
                let name = format!("{kind}-{target}-{seed:016x}-{executed}");
                std::fs::write(dir.join(name), &input).unwrap();
            }
            panic!(
                "{target}: {kind} after {executed} inputs (seed {seed:#x}, {} bytes)",
                input.len()
            );
        }
        executed += 1;
    }
    executed
}

#[test]
fn short_mutation_smoke_over_every_target() {
    for (target, _) in TARGETS {
        let executed = drive(target, 0x0a11_ce5e_ed5e_ed01, 1500, None, None);
        assert_eq!(executed, 1500, "{target}");
    }
}

/// Long run for the runner script. Ignored by default so `cargo test` stays quick.
#[test]
#[ignore = "driven by verification/prototypes/expressive-fuzz/run_fuzz.py"]
fn timed_mutation_run() {
    let target = std::env::var("OM_FUZZ_TARGET").expect("OM_FUZZ_TARGET");
    let seconds: u64 = std::env::var("OM_FUZZ_SECONDS")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(30);
    let seed: u64 = std::env::var("OM_FUZZ_SEED")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(1);
    let artifacts = std::env::var("OM_FUZZ_ARTIFACTS").ok().map(PathBuf::from);
    let started = Instant::now();
    let executed = drive(
        &target,
        seed,
        u64::MAX,
        Some(started + Duration::from_secs(seconds)),
        artifacts.as_deref(),
    );
    println!(
        "OM_FUZZ_RESULT target={target} executed={executed} seconds={:.1}",
        started.elapsed().as_secs_f64()
    );
}

// ------------------------------------------------------------------------------------------- properties

const KINDS: [Kind; 4] = [
    Kind::Sticker,
    Kind::CustomEmoji,
    Kind::ReactionAsset,
    Kind::LoopAnimation,
];

proptest! {
    #![proptest_config(ProptestConfig { cases: 512, failure_persistence: None, ..ProptestConfig::default() })]

    /// Resource-ceiling checks: any claimed facts either fail with a stable code or stay inside the profile budget.
    /// Extreme 32-bit values must be refused by checked arithmetic, never wrap or panic.
    #[test]
    fn claimed_facts_never_exceed_the_budget_or_overflow(
        kind in 0usize..4,
        size in prop_oneof![Just(0usize), Just(1usize), Just(1usize << 20), Just((1usize << 20) + 1), Just(6usize << 20), 0usize..(8 << 20)],
        width in prop_oneof![Just(0u32), Just(1), Just(256), Just(257), Just(512), Just(513), Just(1024), Just(1025), Just(u32::MAX), any::<u32>()],
        height in prop_oneof![Just(0u32), Just(1), Just(256), Just(512), Just(1024), Just(u32::MAX), any::<u32>()],
        animated in any::<bool>(),
        frames in proptest::collection::vec(
            (prop_oneof![Just(0u32), any::<u32>()], prop_oneof![Just(0u32), any::<u32>()],
             prop_oneof![Just(1u32), Just(512), Just(1024), Just(u32::MAX), any::<u32>()],
             prop_oneof![Just(1u32), Just(512), Just(1024), Just(u32::MAX), any::<u32>()],
             prop_oneof![Just(0u32), Just(33), Just(10_000), Just(u32::MAX), any::<u32>()]),
            0..400),
    ) {
        let frames: Vec<Frame> = frames
            .into_iter()
            .map(|(x, y, width, height, duration_ms)| Frame { x, y, width, height, duration_ms })
            .collect();
        let kind = KINDS[kind];
        if let Ok(facts) = validate_facts(kind, size, width, height, animated, &frames) {
            prop_assert_eq!(facts.frames as usize, frames.len());
            prop_assert!(u64::from(facts.total_pixels) <= 1024 * 1024 * 300);
            prop_assert!(facts.encoded_size == size && size > 0);
        }
    }

    /// Whatever the bytes, no target panics and each target's answer is a pure function of its input.
    #[test]
    fn arbitrary_bytes_never_panic_any_target(data in proptest::collection::vec(any::<u8>(), 0..2048)) {
        for (_, run) in TARGETS {
            let first = run(&data);
            prop_assert_eq!(first, run(&data));
        }
    }
}

