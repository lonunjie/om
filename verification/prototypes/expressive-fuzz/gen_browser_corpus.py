"""Derive the small checked-in corpus of the browser-path fuzz (V-012) from the seed corpus.

The browser harness (packages/om-web-platform/src/expressive/fuzz.test.ts) needs WebP header shapes only, so it takes every
`webp` seed of at most 512 bytes. Output: packages/om-web-platform/src/expressive/fuzz-corpus.ts, `export const corpus = {"webp": {file: hex}}`.

    python3 gen_browser_corpus.py            # rewrite the corpus
    python3 gen_browser_corpus.py --check    # fail if it differs
"""
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / "packages/om-web-platform/src/expressive/fuzz-corpus.ts"
LIMIT = 512

seeds = json.loads(gzip.decompress((HERE / "seeds.json.gz").read_bytes()))
corpus = {"webp": {k: v for k, v in sorted(seeds["webp"].items()) if len(v) // 2 <= LIMIT}}
text = (
    "// Generated by verification/prototypes/expressive-fuzz/gen_browser_corpus.py; do not edit.\n"
    "export const corpus = " + json.dumps(corpus, indent=1, sort_keys=True) + " as const;\n"
)
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        print("browser fuzz corpus differs from what gen_browser_corpus.py writes", file=sys.stderr)
        sys.exit(1)
    print(f"browser corpus current: {len(corpus['webp'])} files")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(corpus['webp'])} files")
