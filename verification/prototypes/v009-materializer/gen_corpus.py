KINDS = ["pin", "redact", "vote", "close", "tcreate", "tupdate", "tstatus", "mtopic", "edit", "react", "delete"]


def build_random(n_cases: int, seed: int):
    rng = random.Random(seed)
    actors = ["A", "M", "B", "C", "X"]
    for i in range(n_cases):
        ctl = control(({}, {}), ({}, {rng.choice(actors): [rng.choice(ALL)]}))
        events = [msg("m1", rng.choice(["A", "B"]), 0), msg("m2", "B", 1), poll("poll", "A", 2, mode=rng.choice(["single", "multiple"]))]
        n = rng.randint(4, 6)
        for j in range(n):
            a, t, e = rng.choice(actors), rng.randint(3, 12), rng.choice([0, 1])
            eid = f"r{j}"
            k = rng.choice(KINDS)
            target = rng.choice(["m1", "m2", "poll", "ghost"]) if rng.random() < 0.9 else "m1"
            if k == "pin":
                x = pin(eid, a, t, target, rng.random() < 0.6, epoch=e)
            elif k == "redact":
                x = redact(eid, a, t, target, epoch=e)
            elif k == "vote":
                x = vote(eid, a, t, rng.choice(["poll", "m1"]), rng.sample(["x", "y", "z", "w"], rng.randint(0, 2)), epoch=e)
            elif k == "close":
                x = close(eid, a, t, "poll", epoch=e)
            elif k == "tcreate":
                x = tcreate(eid, a, t, rng.choice(["t1", "t2"]), f"title{j}", epoch=e)
            elif k == "tupdate":
                x = tupdate(eid, a, t, rng.choice(["t1", "t2"]), f"upd{j}", epoch=e)
            elif k == "tstatus":
                x = tstatus(eid, a, t, "t1", rng.choice(["open", "resolved", "archived"]), epoch=e)
            elif k == "mtopic":
                x = mtopic(eid, a, t, rng.choice(["m1", "m2"]), rng.choice(["t1", "t2"]), epoch=e)
            elif k == "edit":
                x = op("message.edit", eid, a, t, {"target_event_id": target, "replacement": f"ed{j}"}, epoch=e)
            elif k == "react":
                x = op("reaction.set", eid, a, t, {"target_event_id": target, "reaction_key": rng.choice(["+1", "ok"]), "present": rng.random() < 0.7}, epoch=e)
            else:
                x = op("message.delete", eid, a, t, {"target_event_id": target}, epoch=e)
            r = rng.random()
            if r < 0.06:
                x["body"] = {**x["body"], "target_event_id": 42}  # wrong type
            elif r < 0.10:
                x["required_capabilities"] = ["org.example.unknown"]
